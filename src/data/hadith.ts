/** Deterministic "hadith of the day" by date. */
export function hadithOfTheDay(date: Date = new Date()): Hadith {
  const seed = date.getFullYear() * 1000 + Math.floor(date.getTime() / 86400000);
  return HADITHS[Math.abs(seed) % HADITHS.length];
}

/** Get the hadith meaning text in the user's language (falls back to English). */
export function hadithText(h: Hadith, lang: string): string {
  if (lang === 'hi') return h.hi;
  if (lang === 'ur') return h.ur;
  return h.en;
}
